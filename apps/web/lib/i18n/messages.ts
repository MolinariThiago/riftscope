const dictionaries: Record<Locale, Dict> = { en, es, pt };

/** Resolve a dot-path from the dictionary, falling back to the key itself. */
export function translate(locale: Locale, path: string): string {
  const dict = dictionaries[locale] ?? en;
  const parts = path.split(".");
  let cur: unknown = dict;
  for (const p of parts) {
    if (typeof cur === "object" && cur !== null && p in cur) {
      cur = (cur as Record<string, unknown>)[p];
    } else {
      // Fallback to English
      let fb: unknown = en;
      for (const q of parts) {
        if (typeof fb === "object" && fb !== null && q in fb) {
          fb = (fb as Record<string, unknown>)[q];
        } else {
          return path;
        }
      }
      return typeof fb === "string" ? fb : path;
    }
  }
  return typeof cur === "string" ? cur : path;
}
